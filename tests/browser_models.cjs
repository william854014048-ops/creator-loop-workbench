/* Named model settings in isolated Edge; no external API requests. */
const assert = require('node:assert/strict');
const {chromium} = require('playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const url = process.env.LOOP_FIXTURE_URL;
assert.ok(url, 'Set LOOP_FIXTURE_URL to an isolated fixture.');
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const context = await browser.newContext({viewport: {width: 1200, height: 900}});
  const page = await context.newPage();
  const errors = [], passed = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = text => { passed.push(text); process.stdout.write('PASS ' + text + '\n'); };
  const open = async () => { await page.locator('#open-settings').click(); await page.locator('#settings-dialog[open]').waitFor(); };
  const save = async () => { await page.getByRole('button', {name: '保存并使用', exact: true}).click(); await page.waitForFunction(() => !document.querySelector('#settings-dialog').open); };
  try {
    await page.goto(url);
    await open();
    assert.equal(await page.locator('#new-model-profile').count(), 1, 'Named model creation control must exist');
    await page.locator('#new-model-profile').click();
    await page.locator('#model-profile-name').fill('GPT 试用');
    await page.locator('#model-provider').selectOption('responses');
    await page.locator('#model-base-url').fill('https://responses.example/v1');
    await page.locator('#model-name').fill('gpt-test');
    await page.locator('#model-key').fill('mock-key-one');
    await page.locator('#model-output-limit').fill('32768');
    await save();
    await open();
    assert.equal(await page.locator('#model-profile-name').inputValue(), 'GPT 试用');
    assert.equal(await page.locator('#model-key').inputValue(), '');
    assert.ok((await page.locator('#key-status').innerText()).includes('已加密保存'));
    check('命名配置可创建、保存、重开，密钥保持隐藏');
    const firstId = await page.locator('#saved-model-profile').inputValue();
    await page.locator('#new-model-profile').click();
    await page.locator('#model-profile-name').fill('GPT 审稿');
    await page.locator('#model-provider').selectOption('responses');
    await page.locator('#model-base-url').fill('https://responses.example/v1');
    await page.locator('#model-name').fill('gpt-review');
    await page.locator('#model-key').fill('mock-key-two');
    await save();
    await open();
    const secondId = await page.locator('#saved-model-profile').inputValue();
    assert.notEqual(firstId, secondId);
    await page.locator('#saved-model-profile').selectOption(firstId);
    assert.equal(await page.locator('#model-name').inputValue(), 'gpt-test');
    await page.locator('#model-profile-name').fill('GPT 日常');
    await page.locator('#model-output-limit').fill('49152');
    await save();
    await page.reload();
    await open();
    assert.equal(await page.locator('#model-profile-name').inputValue(), 'GPT 日常');
    assert.equal(await page.locator('#model-output-limit').inputValue(), '49152');
    await page.locator('#saved-model-profile').selectOption(secondId);
    assert.equal(await page.locator('#model-name').inputValue(), 'gpt-review');
    assert.ok((await page.locator('#key-status').innerText()).includes('已加密保存'));
    check('同协议多配置互不覆盖，切换、重命名与输出额度持久保存');
    await page.locator('#model-key').fill('must-not-follow-selection');
    await page.locator('#saved-model-profile').selectOption(firstId);
    assert.equal(await page.locator('#model-key').inputValue(), '');
    await page.locator('#new-model-profile').click();
    assert.ok((await page.locator('#key-status').innerText()).includes('尚未填写'));
    await page.locator('#model-profile-name').fill('临时测试');
    await page.locator('#model-name').fill('temporary-model');
    let preview;
    await page.route('**/api/settings/test', async route => {
      preview = route.request().postDataJSON();
      await route.fulfill({json: {ok: true, message: '连接成功'}});
    });
    await page.locator('#test-model').click();
    await page.waitForFunction(() => document.querySelector('#settings-notice').textContent.includes('连接成功'));
    assert.equal(preview.new_profile, true);
    assert.equal(preview.name, '临时测试');
    await page.locator('#close-settings').click();
    await open();
    assert.equal(await page.locator('#model-profile-name').inputValue(), 'GPT 日常');
    check('选配置清空临时密钥，新配置测试不保存、不切换当前配置');
    await page.setViewportSize({width: 390, height: 844});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    const qa = path.join(__dirname, '../runtime/qa');
    fs.mkdirSync(qa, {recursive: true});
    await page.screenshot({path: path.join(qa, '多模型配置-手机.png'), fullPage: true});
    check('设置页面手机可用，无脚本错误');
    fs.writeFileSync(path.join(qa, 'model-browser-results.json'), JSON.stringify({passed, errors}, null, 2), 'utf8');
  } finally { await context.close(); await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
